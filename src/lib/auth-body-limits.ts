// 未認証で到達できる認証系 POST 2 経路 (SSO ACS / マジックリンクのコールバック) が
// 受け付けるリクエストボディの「受け入れ枠」— 最大バイト数。
//
// なぜ route ファイルではなくここに置くのか (`webhook-body-limits.ts` と同じ理由):
// Next.js の Route Handler は既知のエクスポート名 (GET/POST/runtime 等) しか許さないため、
// route.ts から定数を export できない。route とテストが同じ定義を参照する (= 片方だけ値を
// 変えたら気付ける) ようにするには、両者から import できる場所へ出す必要がある。
//
// **なぜ「その経路の他の共有定数と同居」をやめてここへ分けたのか。**
// 元は SSO ACS の枠が `sso-rate-limit.ts`、コールバックの枠が `magic-link.ts` にあり、
// 「未認証リクエストの受け入れ枠」をレート制限と並べて読める利点があった。しかし
// `entry-body-limit.ts` が入口の枠を導出するためにこの 2 つを読むようになり、
// **`next.config.ts` の読み込みグラフに入った**。そのグラフに入るモジュールは
// `@/` エイリアスを使えない (Next.js の config transpile が推移的な `paths` を解決しない) ため、
// 同居のままだと `magic-link.ts` (トークン生成・HTML メール描画) と `sso-rate-limit.ts`、
// さらに `html-escape.ts` にまで「相対 import のままにすること」という制約が伝播する。
// **実行時コードを持つモジュールに、値を 1 つ読ませるためだけの制約を課さない。**
// 定数だけのファイルに切り出せば、制約は定数ファイルの中で閉じる。
//
// 実際の読み取り (ストリームを上限つきで読み、超えた時点で打ち切る) は
// `request-body-limit.ts` の `readFormWithinByteLimit` が担う。上限値をここで決め、
// 読み取り方法をあちらに集約する分担にしている。
//
// 値を決めるときの注意: 読み取り中の一時コピーを含めて、本文サイズの約 3 倍のメモリを
// 見込むこと (内訳は request-body-limit.ts 冒頭の「メモリの目安」)。加えて入口の複製ぶんが
// 上乗せされる (`entry-body-limit.ts`)。

// ACS (POST /api/auth/sso/<tenantId>/acs) が受け付けるリクエストボディの最大バイト数 (1MB)。
// SAML アサーションは署名・証明書込みでも通常数十 KB で、属性が多いディレクトリでも
// base64 + URL エンコード後に 1MB へ届くことはまず無い。一方 ACS は未認証で到達でき、
// フォームのパースはボディ全体をメモリに載せるため、上限が無いと巨大ボディの送り付けで
// メモリを枯渇させられる (§9)。
export const SSO_ACS_MAX_BODY_BYTES = 1024 * 1024;

// コールバック (POST /api/auth/magic-link/callback) が受け付けるリクエストボディの最大バイト数 (64KB)。
// このフォームが運ぶのはトークン 1 つ (43 文字の base64url) だけなので 64KB でも桁違いに余裕がある。
// 上限を置くのは、この経路が未認証で到達でき、フォームのパースがボディ全体をメモリに載せるため
// (§9)。レート制限は毎分のリクエスト数しか数えないので、1 本あたりのサイズは別に縛る必要がある。
export const MAGIC_LINK_CALLBACK_MAX_BODY_BYTES = 64 * 1024;
