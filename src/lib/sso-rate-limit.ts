// SSO (SAML) エンドポイント群 (acs/login/metadata) が共有するレート制限の定数。
// /code-review ultra 指摘対応: 「固定キーの全体制限 (60秒60回) → tenantId 確定後の
// テナント単位制限 (60秒20回)」という同一の制限値・エラーメッセージが acs/route.ts・
// login/route.ts・metadata/route.ts の 3 箇所に複製されていたため (CLAUDE.md §6
// 「2〜3 箇所目で共通化する」を超過)、ここに集約する。
//
// tenantId は DB 検証前 (URL セグメント) の値で攻撃者が自由に変更できるため、これ単体を
// キーにすると値を変えるだけで無制限に回避されてしまう。そのためテナント解決 (DB 参照) より
// 前に固定キーで全体の上限を設け、テナントの実在・SSO 有効性を確認できた後にさらに
// tenantId (DB 由来で信頼できる値) をキーにしたテナント単位の制限を重ねる二段構えにする。

// 固定キーの全体レート制限 (テナント解決前に適用)
export const SSO_UNAUTHENTICATED_RATE_LIMIT = { limit: 60, windowMs: 60_000 } as const;

// テナント単位のレート制限 (テナントの実在・SSO 有効性を確認できた後に適用)。
// ACS ではこれを「署名検証を通過した後」に適用する (下の未検証枠のコメント参照)
export const SSO_TENANT_RATE_LIMIT = { limit: 20, windowMs: 60_000 } as const;

// ACS 専用: 署名検証より前 (XML パースの手前) で適用するテナント単位の枠 (issue #315)。
//
// なぜ ACS だけ枠が 2 つ要るか:
//   enforceRateLimit は「通過した時点でバケットを消費する」ため、署名検証より前に置いた枠は
//   検証に落ちるリクエストでも減る。tenantId は SSO ログイン URL に現れる公開値なので、
//   これを知る第三者が出鱈目な SAMLResponse を上限ぶん投げるだけで枠を枯渇させられ、
//   以降 IdP からの正規アサーションまで 429 になる (＝そのテナントの SSO ログインが止まる)。
//   一方で枠を単純に検証の後ろへ動かすと、未認証の XML を無制限にパーサへ通すことになり
//   別のリソース枯渇 (XML 爆弾・巨大アサーション) を招く。そこで枠を 2 つに分ける:
//     - この枠 (検証前): XML パースへ到達する量の頭打ち。検証に落ちる相手も消費する
//     - SSO_TENANT_RATE_LIMIT (検証後): 検証を通った相手のバースト抑制。第三者は消費できない
//
// 値の根拠 (運用上のトレードオフ):
//   検証後の枠 (20/分) の 2 倍を取り、正規ログインぶんを使い切っても毎分 20 件の
//   「検証に落ちる雑音」を吸収できる余裕を残す。全体枠 (60/分) より小さくしているのは、
//   1 テナント宛の雑音だけで全体枠を使い切って他テナントの SSO まで巻き込むのを避けるため。
//
// 残る限界 (この枠では閉じない):
//   検証前に置く枠である以上、未認証の相手がこの枠自体を枯渇させられる点は変わらない
//   (成立に必要な流量が 20/分から 40/分へ上がるだけ)。送信元 IP 単位のバケットを足すかは
//   前段プロキシの構成と併せた別の判断になる (固定キーの全体枠が全テナント共有である点も同じ。
//   issue #315 と PR #314 に記録済み)。
export const SSO_ACS_UNVERIFIED_TENANT_RATE_LIMIT = { limit: 40, windowMs: 60_000 } as const;

// レート制限超過時にクライアントへ返す共通の日本語メッセージ
export const SSO_RATE_LIMIT_MESSAGE = 'しばらく時間をおいて再度お試しください';

